 * 用正则或拼音都推不出来，只有显式列出来才可靠。上游缺一个、错一个，补一条就够，
 * 不牵扯数据库迁移。
 *
 * 匹配口径见 [provinceOf]。识别不出的台由调用方归「其他地方台」，绝不硬塞错省 ——
 * 错归比漏归更糟：用户会在「浙江频道」里翻到一个河北台，然后怀疑整个分组都乱了。
