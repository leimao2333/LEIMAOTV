 * 而「地方频道」里的台名只有「地级市 / 县名 + 频道类型」（如「上虞新闻综合」「哈尔滨娱乐」），
 * 没有任何省份字段。要把它们归进正确的「XX频道」，只能靠地名反查省。
 *
 * 这是一份**手工维护的静态表**（覆盖全部地级行政区 + 常见县级市/县），不是程序自动推导：
